//! Generates the phone app's TypeScript protocol types,
//! `apps/pwa/src/protocol.ts`, by reading `crates/protocol`'s source with
//! `syn`. No protocol type carries a derive for it: the generator knows the
//! serde shapes the protocol uses and refuses any attribute it does not know,
//! so a new shape cannot be emitted wrong silently.

use std::collections::HashSet;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, anyhow, bail};
use syn::meta::ParseNestedMeta;
use syn::{
    Attribute, Expr, Fields, FieldsNamed, GenericArgument, Item, ItemConst, ItemEnum, ItemStruct,
    ItemType, Lit, LitStr, PathArguments, Type, Visibility,
};

/// Where the generated file lives, relative to the workspace root.
pub const OUTPUT_PATH: &str = "apps/pwa/src/protocol.ts";

/// The two comment lines that open the generated file.
const HEADER: &str = "// Generated by tools/protocol-ts from crates/protocol. Do not edit: run `cargo run -p protocol-ts` to regenerate.\n// A daemon newer than this file can send a tag or value these unions do not list: every switch over one keeps a default branch.";

/// The workspace root: this crate's manifest folder's grandparent.
pub fn repo_root() -> Result<PathBuf> {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .map(Path::to_path_buf)
        .context("tools/protocol-ts has no workspace root two folders up")
}

/// Reads the protocol crate's sources under `repo_root` and returns the
/// whole TypeScript file.
pub fn generate(repo_root: &Path) -> Result<String> {
    let read = |rel: &str| {
        let path = repo_root.join(rel);
        std::fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))
    };
    generate_from_sources(
        &read("crates/protocol/src/lib.rs")?,
        &read("crates/protocol/src/env_rows.rs")?,
        &read("crates/protocol/src/error_codes.rs")?,
        &read("protocol-version.json")?,
    )
}

/// The generator over the four sources' text: the protocol crate's `lib.rs`,
/// `env_rows.rs` and `error_codes.rs`, and `protocol-version.json`.
pub fn generate_from_sources(
    lib_rs: &str,
    env_rows: &str,
    error_codes: &str,
    version_json: &str,
) -> Result<String> {
    let lib = syn::parse_file(lib_rs).context("parsing crates/protocol/src/lib.rs")?;
    let env = syn::parse_file(env_rows).context("parsing crates/protocol/src/env_rows.rs")?;
    let codes =
        syn::parse_file(error_codes).context("parsing crates/protocol/src/error_codes.rs")?;

    let mut lib_items = Vec::new();
    collect(&lib.items, &mut lib_items);
    let mut env_items = Vec::new();
    collect(&env.items, &mut env_items);

    let mut known = HashSet::new();
    for item in lib_items.iter().chain(&env_items) {
        if let Some(name) = emitted_name(item)?
            && !known.insert(name.clone())
        {
            bail!("`{name}` is declared twice");
        }
    }

    let mut blocks = vec![HEADER.to_owned()];
    blocks.extend(version_blocks(version_json)?);
    for item in &lib_items {
        if let Some(block) = emit_item(item, &known, true)? {
            blocks.push(block);
        }
    }
    for item in &env_items {
        if let Some(block) = emit_item(item, &known, false)? {
            blocks.push(block);
        }
    }
    if let Some(block) = error_code_block(&codes.items) {
        blocks.push(block);
    }
    let mut out = blocks.join("\n\n");
    out.push('\n');
    Ok(out)
}

