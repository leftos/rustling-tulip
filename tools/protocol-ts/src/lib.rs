/// Every item in source order, inline modules flattened, `#[cfg(test)]`
/// items and modules left out.
fn collect<'a>(items: &'a [Item], out: &mut Vec<&'a Item>) {
    for item in items {
        if is_cfg_test(item_attrs(item)) {
            continue;
        }
        if let Item::Mod(module) = item {
            if let Some((_, inner)) = &module.content {
                collect(inner, out);
            }
            continue;
        }
        out.push(item);
    }
}

fn item_attrs(item: &Item) -> &[Attribute] {
    match item {
        Item::Struct(s) => &s.attrs,
        Item::Enum(e) => &e.attrs,
        Item::Type(t) => &t.attrs,
        Item::Const(c) => &c.attrs,
        Item::Mod(m) => &m.attrs,
        Item::Fn(f) => &f.attrs,
        Item::Impl(i) => &i.attrs,
        _ => &[],
    }
}

fn is_cfg_test(attrs: &[Attribute]) -> bool {
    attrs.iter().any(|attr| {
        attr.path().is_ident("cfg")
            && attr
                .meta
                .require_list()
                .is_ok_and(|list| list.tokens.to_string() == "test")
    })
}

fn is_pub(vis: &Visibility) -> bool {
    matches!(vis, Visibility::Public(_))
}

/// The TypeScript name an item is emitted under, if it is emitted: a `pub`
/// struct or enum deriving `Serialize` or `Deserialize`, or a `pub` type
/// alias.
fn emitted_name(item: &Item) -> Result<Option<String>> {
    Ok(match item {
        Item::Struct(s) if is_pub(&s.vis) && derives_serde(&s.attrs, &s.ident.to_string())? => {
            Some(s.ident.to_string())
        }
        Item::Enum(e) if is_pub(&e.vis) && derives_serde(&e.attrs, &e.ident.to_string())? => {
            Some(e.ident.to_string())
        }
        Item::Type(t) if is_pub(&t.vis) => Some(t.ident.to_string()),
        _ => None,
    })
}

fn derives_serde(attrs: &[Attribute], ctx: &str) -> Result<bool> {
    let mut found = false;
    for attr in attrs {
        if !attr.path().is_ident("derive") {
            continue;
        }
        attr.parse_nested_meta(|meta| {
            if meta
                .path
                .segments
                .last()
                .is_some_and(|s| s.ident == "Serialize" || s.ident == "Deserialize")
            {
                found = true;
            }
            Ok(())
        })
        .map_err(|e| anyhow!("`{ctx}`: reading its derive list: {e}"))?;
    }
    Ok(found)
}

fn emit_item(item: &Item, known: &HashSet<String>, consts: bool) -> Result<Option<String>> {
    if emitted_name(item)?.is_none() {
        return Ok(match item {
            Item::Const(c) if consts => str_const(c).map(|value| {
                format!(
                    "{}export const {} = {};",
                    jsdoc(&docs(&c.attrs), ""),
                    c.ident,
                    js_string(&value)
                )
            }),
            _ => None,
        });
    }
    match item {
        Item::Struct(s) => emit_struct(s, known).map(Some),
        Item::Enum(e) => emit_enum(e, known).map(Some),
        Item::Type(t) => emit_alias(t, known).map(Some),
        _ => Ok(None),
    }
}

/// The value of a `pub const NAME: &str = "…";`.
fn str_const(c: &ItemConst) -> Option<String> {
    let Type::Reference(r) = &*c.ty else {
        return None;
    };
    let Type::Path(p) = &*r.elem else {
        return None;
    };
    if !is_pub(&c.vis) || !p.path.is_ident("str") {
        return None;
    }
    match &*c.expr {
        Expr::Lit(lit) => match &lit.lit {
            Lit::Str(s) => Some(s.value()),
            _ => None,
        },
        _ => None,
    }
}

fn version_blocks(version_json: &str) -> Result<Vec<String>> {
    let value: serde_json::Value =
        serde_json::from_str(version_json).context("parsing protocol-version.json")?;
    let version = value
        .get("version")
        .and_then(serde_json::Value::as_u64)
        .context("protocol-version.json: `version` is not a number")?;
    let supported = value
        .get("supported")
        .and_then(serde_json::Value::as_array)
        .context("protocol-version.json: `supported` is not an array")?
        .iter()
        .map(|v| {
            v.as_u64()
                .map(|n| n.to_string())
                .context("protocol-version.json: a `supported` entry is not a number")
        })
        .collect::<Result<Vec<_>>>()?;
    Ok(vec![
        format!("export const PROTOCOL_VERSION = {version};"),
        format!(
            "export const SUPPORTED_PROTOCOL_VERSIONS: readonly number[] = [{}];",
            supported.join(", ")
        ),
    ])
}

fn error_code_block(items: &[Item]) -> Option<String> {
    let mut entries = String::new();
    for item in items {
        if let Item::Const(c) = item
            && let Some(value) = str_const(c)
        {
            entries.extend([
                jsdoc(&docs(&c.attrs), "  "),
                format!("  {}: {},\n", c.ident, js_string(&value)),
            ]);
        }
    }
    if entries.is_empty() {
        return None;
    }
    Some(format!(
        "export const ErrorCode = {{\n{entries}}} as const;"
    ))
}

fn emit_alias(t: &ItemType, known: &HashSet<String>) -> Result<String> {
    let name = t.ident.to_string();
    if !t.generics.params.is_empty() {
        bail!("`{name}`: a generic type alias is not supported");
    }
    let ty = ts_type(&t.ty, known, &name)?;
    Ok(format!(
        "{}export type {name} = {};",
        jsdoc(&docs(&t.attrs), ""),
        ty.text
    ))
}

fn emit_struct(s: &ItemStruct, known: &HashSet<String>) -> Result<String> {
    let name = s.ident.to_string();
    if !s.generics.params.is_empty() {
        bail!("`{name}`: a generic struct is not supported");
    }
    let attrs = serde_attrs(
        &s.attrs,
        &name,
        &["rename_all", "default", "transparent"],
        "a struct",
    )?;
    let doc = jsdoc(&docs(&s.attrs), "");
    if attrs.transparent {
        let mut fields = s.fields.iter();
        let (Some(field), None) = (fields.next(), fields.next()) else {
            bail!("`{name}`: #[serde(transparent)] needs exactly one field");
        };
        serde_attrs(&field.attrs, &name, &[], "a transparent struct's field")?;
        let ty = ts_type(&field.ty, known, &name)?;
        return Ok(format!("{doc}export type {name} = {};", ty.text));
    }
    match &s.fields {
        Fields::Named(named) => {
            let fields = named_fields(
                named,
                attrs.rename_all.as_deref(),
                attrs.default,
                known,
                &name,
            )?;
            if fields.is_empty() {
                return Ok(format!("{doc}export interface {name} {{}}"));
            }
            let mut body = String::new();
            for f in &fields {
                body.extend([jsdoc(&f.doc, "  "), format!("  {};\n", f.property())]);
            }
            Ok(format!("{doc}export interface {name} {{\n{body}}}"))
        }
        Fields::Unnamed(_) => bail!(
            "`{name}`: a tuple struct is not supported (only #[serde(transparent)] newtypes are)"
        ),
        Fields::Unit => Ok(format!("{doc}export type {name} = null;")),
    }
}

fn emit_enum(e: &ItemEnum, known: &HashSet<String>) -> Result<String> {
    let name = e.ident.to_string();
    if !e.generics.params.is_empty() {
        bail!("`{name}`: a generic enum is not supported");
    }
    let attrs = serde_attrs(
        &e.attrs,
        &name,
        &["tag", "content", "rename_all", "untagged"],
        "an enum",
    )?;
    if attrs.untagged && attrs.tag.is_some() {
        bail!("`{name}`: #[serde(untagged)] with a `tag` is not supported");
    }
    if attrs.content.is_some() && attrs.tag.is_none() {
        bail!("`{name}`: #[serde(content)] without a `tag` is not supported");
    }
    let mut members = Vec::new();
    for v in &e.variants {
        let ctx = format!("{name}::{}", v.ident);
        let vattrs = serde_attrs(
            &v.attrs,
            &ctx,
            &["rename", "rename_all", "other"],
            "a variant",
        )?;
        if vattrs.other {
            if !matches!(v.fields, Fields::Unit) {
                bail!("`{ctx}`: #[serde(other)] on a variant that is not a unit variant");
            }
            continue;
        }
        let wire = match vattrs.rename {
            Some(rename) => rename,
            None => rename_variant(&unraw(&v.ident), attrs.rename_all.as_deref(), &ctx)?,
        };
        let shape = VariantShape {
            enum_attrs: &attrs,
            variant_rename_all: vattrs.rename_all.as_deref(),
            wire: &wire,
            ctx: &ctx,
            known,
        };
        let (text, field_docs) = shape.member(&v.fields)?;
        members.push((fold_docs(docs(&v.attrs), &field_docs), text));
    }
    let doc = jsdoc(&docs(&e.attrs), "");
    if members.is_empty() {
        return Ok(format!("{doc}export type {name} = never;"));
    }
    let mut out = format!("{doc}export type {name} =");
    for (member_doc, text) in &members {
        out.extend([
            "\n".to_owned(),
            jsdoc(member_doc, "  "),
            format!("  | {text}"),
        ]);
    }
    out.push(';');
    Ok(out)
}

/// One enum variant's place in its enum's union.
struct VariantShape<'a> {
    enum_attrs: &'a SerdeAttrs,
    variant_rename_all: Option<&'a str>,
    wire: &'a str,
    ctx: &'a str,
    known: &'a HashSet<String>,
}

impl VariantShape<'_> {
    /// The union member's text, and the variant's fields with their docs
    /// (an inline object has no room for a field's own doc block).
    fn member(&self, fields: &Fields) -> Result<(String, Vec<TsField>)> {
        let attrs = self.enum_attrs;
        let named = match fields {
            Fields::Named(named) => {
                named_fields(named, self.variant_rename_all, false, self.known, self.ctx)?
            }
            _ => Vec::new(),
        };
        let text = if attrs.untagged {
            match fields {
                Fields::Unit => "null".to_owned(),
                Fields::Named(_) => object(&[], &named),
                Fields::Unnamed(_) => self.unnamed(fields)?,
            }
        } else if let Some(tag) = &attrs.tag {
            let tag_pair = format!("{}: {}", prop_key(tag), js_string(self.wire));
            match (fields, &attrs.content) {
                (Fields::Unit, _) => object(&[tag_pair], &[]),
                (Fields::Named(_), None) => object(&[tag_pair], &named),
                (Fields::Named(_), Some(content)) => object(
                    &[
                        tag_pair,
                        format!("{}: {}", prop_key(content), object(&[], &named)),
                    ],
                    &[],
                ),
                (Fields::Unnamed(_), Some(content)) => object(
                    &[
                        tag_pair,
                        format!("{}: {}", prop_key(content), self.unnamed(fields)?),
                    ],
                    &[],
                ),
                (Fields::Unnamed(unnamed), None) => {
                    let mut iter = unnamed.unnamed.iter();
                    let (Some(field), None) = (iter.next(), iter.next()) else {
                        bail!(
                            "`{}`: an internally tagged tuple variant is not supported",
                            self.ctx
                        );
                    };
                    let inner = ts_type(&field.ty, self.known, self.ctx)?;
                    if inner.union || !self.known.contains(&inner.text) {
                        bail!(
                            "`{}`: an internally tagged newtype variant must wrap an emitted type, not `{}`",
                            self.ctx,
                            inner.text
                        );
                    }
                    format!("({} & {})", object(&[tag_pair], &[]), inner.text)
                }
            }
        } else {
            match fields {
                Fields::Unit => js_string(self.wire),
                _ => bail!(
                    "`{}`: an externally tagged enum with a non-unit variant is not supported",
                    self.ctx
                ),
            }
        };
        Ok((text, named))
    }

    /// A tuple variant's content: the one field's type, or a tuple of them.
    fn unnamed(&self, fields: &Fields) -> Result<String> {
        let types = fields
            .iter()
            .map(|f| {
                serde_attrs(&f.attrs, self.ctx, &[], "a tuple variant's field")?;
                ts_type(&f.ty, self.known, self.ctx)
            })
            .collect::<Result<Vec<_>>>()?;
        Ok(match types.as_slice() {
            [one] => one.text.clone(),
            many => format!(
                "[{}]",
                many.iter()
                    .map(|t| t.text.as_str())
                    .collect::<Vec<_>>()
                    .join(", ")
            ),
        })
    }
}

