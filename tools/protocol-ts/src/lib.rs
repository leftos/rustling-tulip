fn unraw(ident: &syn::Ident) -> String {
    let s = ident.to_string();
    s.strip_prefix("r#")
        .map_or_else(|| s.clone(), str::to_owned)
}

/// Serde's `rename_all` on a variant name (written `PascalCase`).
fn rename_variant(variant: &str, rule: Option<&str>, ctx: &str) -> Result<String> {
    let snake = || {
        let mut out = String::new();
        for (i, c) in variant.chars().enumerate() {
            if c.is_uppercase() && i > 0 {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        }
        out
    };
    Ok(match rule {
        None | Some("PascalCase") => variant.to_owned(),
        Some("lowercase") => variant.to_ascii_lowercase(),
        Some("UPPERCASE") => variant.to_ascii_uppercase(),
        Some("camelCase") => lower_first(variant),
        Some("snake_case") => snake(),
        Some("SCREAMING_SNAKE_CASE") => snake().to_ascii_uppercase(),
        Some("kebab-case") => snake().replace('_', "-"),
        Some("SCREAMING-KEBAB-CASE") => snake().replace('_', "-").to_ascii_uppercase(),
        Some(other) => bail!("`{ctx}`: unknown rename_all rule `{other}`"),
    })
}

/// Serde's `rename_all` on a field name (written `snake_case`).
fn rename_field(field: &str, rule: Option<&str>, ctx: &str) -> Result<String> {
    let pascal = || {
        let mut out = String::new();
        let mut upper = true;
        for c in field.chars() {
            if c == '_' {
                upper = true;
            } else if upper {
                out.push(c.to_ascii_uppercase());
                upper = false;
            } else {
                out.push(c);
            }
        }
        out
    };
    Ok(match rule {
        None | Some("snake_case" | "lowercase") => field.to_owned(),
        Some("UPPERCASE" | "SCREAMING_SNAKE_CASE") => field.to_ascii_uppercase(),
        Some("PascalCase") => pascal(),
        Some("camelCase") => lower_first(&pascal()),
        Some("kebab-case") => field.replace('_', "-"),
        Some("SCREAMING-KEBAB-CASE") => field.replace('_', "-").to_ascii_uppercase(),
        Some(other) => bail!("`{ctx}`: unknown rename_all rule `{other}`"),
    })
}

fn lower_first(s: &str) -> String {
    let mut chars = s.chars();
    chars.next().map_or_else(String::new, |first| {
        first.to_ascii_lowercase().to_string() + chars.as_str()
    })
}

/// A property key: bare when it is a JavaScript identifier, else quoted.
fn prop_key(name: &str) -> String {
    let mut chars = name.chars();
    let ident = chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_' || c == '$')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$');
    if ident {
        name.to_owned()
    } else {
        js_string(name)
    }
}

/// A JavaScript string literal: JSON's string syntax is valid JavaScript.
fn js_string(value: &str) -> String {
    serde_json::Value::String(value.to_owned()).to_string()
}

