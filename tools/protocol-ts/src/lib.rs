/// An item's doc comment, one entry per line, leading and trailing blank
/// lines dropped.
fn docs(attrs: &[Attribute]) -> Vec<String> {
    let mut lines = Vec::new();
    for attr in attrs {
        if !attr.path().is_ident("doc") {
            continue;
        }
        let syn::Meta::NameValue(nv) = &attr.meta else {
            continue;
        };
        let Expr::Lit(lit) = &nv.value else {
            continue;
        };
        let Lit::Str(s) = &lit.lit else {
            continue;
        };
        for line in s.value().split('\n') {
            lines.push(line.strip_prefix(' ').unwrap_or(line).trim_end().to_owned());
        }
    }
    while lines.first().is_some_and(String::is_empty) {
        lines.remove(0);
    }
    while lines.last().is_some_and(String::is_empty) {
        lines.pop();
    }
    lines
}

/// A `/** … */` block at `indent`, ending in a newline; empty for no lines.
fn jsdoc(lines: &[String], indent: &str) -> String {
    let lines: Vec<String> = lines.iter().map(|l| l.replace("*/", "*\\/")).collect();
    match lines.as_slice() {
        [] => String::new(),
        [one] => format!("{indent}/** {one} */\n"),
        many => {
            let mut out = vec![format!("{indent}/**")];
            out.extend(many.iter().map(|line| {
                if line.is_empty() {
                    format!("{indent} *")
                } else {
                    format!("{indent} * {line}")
                }
            }));
            out.extend([format!("{indent} */"), String::new()]);
            out.join("\n")
        }
    }
}

