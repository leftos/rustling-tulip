/// The serde attributes the generator knows, read from one site.
#[derive(Default)]
#[expect(
    clippy::struct_excessive_bools,
    reason = "one flag per serde attribute the generator knows"
)]
struct SerdeAttrs {
    keys: Vec<String>,
    tag: Option<String>,
    content: Option<String>,
    rename_all: Option<String>,
    rename: Option<String>,
    default: bool,
    skip_serializing_if: bool,
    untagged: bool,
    transparent: bool,
    other: bool,
}

/// Reads the `#[serde(...)]` attributes at one site. A key outside the known
/// set, or one not in `allowed` for this site, is an error naming `ctx`.
fn serde_attrs(attrs: &[Attribute], ctx: &str, allowed: &[&str], site: &str) -> Result<SerdeAttrs> {
    let mut out = SerdeAttrs::default();
    for attr in attrs {
        if attr.path().is_ident("cfg_attr") && type_tokens(attr).contains("serde") {
            bail!("`{ctx}`: a serde attribute under cfg_attr is not supported");
        }
        if !attr.path().is_ident("serde") {
            continue;
        }
        attr.parse_nested_meta(|meta| read_serde_key(&meta, &mut out))
            .map_err(|e| anyhow!("`{ctx}`: {e}"))?;
    }
    if let Some(key) = out.keys.iter().find(|k| !allowed.contains(&k.as_str())) {
        bail!("`{ctx}`: serde attribute `{key}` is not supported on {site}");
    }
    Ok(out)
}

fn read_serde_key(meta: &ParseNestedMeta, out: &mut SerdeAttrs) -> syn::Result<()> {
    let key = path_string(&meta.path);
    match key.as_str() {
        "tag" => out.tag = Some(lit_str(meta)?),
        "content" => out.content = Some(lit_str(meta)?),
        "rename_all" => out.rename_all = Some(lit_str(meta)?),
        "rename" => out.rename = Some(lit_str(meta)?),
        "default" => {
            if meta.input.peek(syn::Token![=]) {
                lit_str(meta)?;
            }
            out.default = true;
        }
        "skip_serializing_if" => {
            lit_str(meta)?;
            out.skip_serializing_if = true;
        }
        "untagged" => out.untagged = true,
        "transparent" => out.transparent = true,
        "other" => out.other = true,
        _ => return Err(meta.error(format!("unknown serde attribute `{key}`"))),
    }
    out.keys.push(key);
    Ok(())
}

fn lit_str(meta: &ParseNestedMeta) -> syn::Result<String> {
    let value: LitStr = meta.value()?.parse()?;
    Ok(value.value())
}

fn type_tokens(attr: &Attribute) -> String {
    attr.meta
        .require_list()
        .map(|list| list.tokens.to_string())
        .unwrap_or_default()
}

