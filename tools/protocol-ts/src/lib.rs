struct TsField {
    name: String,
    optional: bool,
    ty: String,
    doc: Vec<String>,
}

impl TsField {
    fn property(&self) -> String {
        let mark = if self.optional { "?" } else { "" };
        format!("{}{mark}: {}", prop_key(&self.name), self.ty)
    }
}

fn named_fields(
    named: &FieldsNamed,
    rename_all: Option<&str>,
    container_default: bool,
    known: &HashSet<String>,
    ctx: &str,
) -> Result<Vec<TsField>> {
    named
        .named
        .iter()
        .map(|field| {
            let ident = field
                .ident
                .as_ref()
                .map(unraw)
                .context(format!("`{ctx}`: a named field without a name"))?;
            let fctx = format!("{ctx}.{ident}");
            let attrs = serde_attrs(
                &field.attrs,
                &fctx,
                &["rename", "default", "skip_serializing_if"],
                "a field",
            )?;
            let name = match attrs.rename {
                Some(rename) => rename,
                None => rename_field(&ident, rename_all, &fctx)?,
            };
            Ok(TsField {
                name,
                optional: container_default || attrs.default || attrs.skip_serializing_if,
                ty: ts_type(&field.ty, known, &fctx)?.text,
                doc: docs(&field.attrs),
            })
        })
        .collect()
}

/// An inline object type: the leading pairs (a tag), then the fields.
fn object(lead: &[String], fields: &[TsField]) -> String {
    let parts: Vec<String> = lead
        .iter()
        .cloned()
        .chain(fields.iter().map(TsField::property))
        .collect();
    if parts.is_empty() {
        "{}".to_owned()
    } else {
        format!("{{ {} }}", parts.join("; "))
    }
}

/// A variant's doc, then one paragraph per documented field: an inline
/// object member has no room for its fields' own doc blocks.
fn fold_docs(mut doc: Vec<String>, fields: &[TsField]) -> Vec<String> {
    for field in fields {
        let mut lines = field.doc.iter();
        if let Some(first) = lines.next() {
            if !doc.is_empty() {
                doc.push(String::new());
            }
            doc.push(format!("`{}`: {first}", field.name));
            doc.extend(lines.cloned());
        }
    }
    doc
}

