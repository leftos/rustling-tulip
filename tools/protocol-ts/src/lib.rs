/// A TypeScript type, and whether it is a bare union (needs parentheses as
/// an array element).
struct Ts {
    text: String,
    union: bool,
}

impl Ts {
    fn plain(text: impl Into<String>) -> Self {
        Ts {
            text: text.into(),
            union: false,
        }
    }
}

fn ts_type(ty: &Type, known: &HashSet<String>, ctx: &str) -> Result<Ts> {
    match ty {
        Type::Reference(r) => ts_type(&r.elem, known, ctx),
        Type::Paren(p) => ts_type(&p.elem, known, ctx),
        Type::Group(g) => ts_type(&g.elem, known, ctx),
        Type::Tuple(t) if t.elems.is_empty() => Ok(Ts::plain("null")),
        Type::Tuple(t) => {
            let elems = t
                .elems
                .iter()
                .map(|e| ts_type(e, known, ctx).map(|t| t.text))
                .collect::<Result<Vec<_>>>()?;
            Ok(Ts::plain(format!("[{}]", elems.join(", "))))
        }
        Type::Path(p) if p.qself.is_none() => path_type(&p.path, known, ctx),
        _ => bail!(
            "`{ctx}`: type `{}` is neither an emitted protocol type nor a mapped type",
            type_string(ty)
        ),
    }
}

fn path_type(path: &syn::Path, known: &HashSet<String>, ctx: &str) -> Result<Ts> {
    let Some(last) = path.segments.last() else {
        bail!("`{ctx}`: an empty type path");
    };
    let name = last.ident.to_string();
    let args: Vec<&Type> = match &last.arguments {
        PathArguments::AngleBracketed(a) => a
            .args
            .iter()
            .filter_map(|arg| match arg {
                GenericArgument::Type(t) => Some(t),
                _ => None,
            })
            .collect(),
        _ => Vec::new(),
    };
    let first = path.segments.first().map(|s| s.ident.to_string());
    let arg = |i: usize| -> Result<Ts> {
        let ty = args
            .get(i)
            .with_context(|| format!("`{ctx}`: `{name}` is missing a type argument"))?;
        ts_type(ty, known, ctx)
    };
    if args.is_empty() && known.contains(&name) {
        return Ok(Ts::plain(name));
    }
    let is_chrono = first.as_deref() == Some("chrono");
    Ok(match name.as_str() {
        "String" | "str" | "char" | "PathBuf" | "DateTime" | "NaiveDateTime" | "NaiveDate"
        | "NaiveTime" => Ts::plain("string"),
        _ if is_chrono => Ts::plain("string"),
        "bool" => Ts::plain("boolean"),
        "u8" | "u16" | "u32" | "u64" | "u128" | "usize" | "i8" | "i16" | "i32" | "i64" | "i128"
        | "isize" | "f32" | "f64" => Ts::plain("number"),
        "Value" if path.segments.len() == 1 || first.as_deref() == Some("serde_json") => {
            Ts::plain("unknown")
        }
        "Option" => Ts {
            text: format!("{} | null", arg(0)?.text),
            union: true,
        },
        "Vec" | "VecDeque" | "BTreeSet" | "HashSet" => {
            let elem = arg(0)?;
            if elem.union {
                Ts::plain(format!("({})[]", elem.text))
            } else {
                Ts::plain(format!("{}[]", elem.text))
            }
        }
        "BTreeMap" | "HashMap" => Ts::plain(format!("Record<string, {}>", arg(1)?.text)),
        "Box" | "Arc" => arg(0)?,
        _ => bail!(
            "`{ctx}`: type `{}` is neither an emitted protocol type nor a mapped type",
            path_string(path)
        ),
    })
}

fn type_string(ty: &Type) -> &'static str {
    match ty {
        Type::Array(_) => "fixed-size array",
        Type::Slice(_) => "slice",
        Type::Ptr(_) => "raw pointer",
        Type::BareFn(_) => "function pointer",
        Type::ImplTrait(_) => "impl Trait",
        Type::TraitObject(_) => "dyn Trait",
        Type::Never(_) => "!",
        Type::Path(_) => "qualified path",
        _ => "unrecognised type",
    }
}

fn path_string(path: &syn::Path) -> String {
    path.segments
        .iter()
        .map(|s| s.ident.to_string())
        .collect::<Vec<_>>()
        .join("::")
}

